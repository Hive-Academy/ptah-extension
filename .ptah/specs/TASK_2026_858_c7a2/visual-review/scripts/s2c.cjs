const {launch,OUT}=require('./lib.cjs'); const H=require('./h.cjs'); const fs=require('fs');
(async()=>{const {app,page}=await launch();
 await page.evaluate(H.INS);
 console.log('home:',await page.evaluate(()=>document.body.innerText.replace(/\n/g,' | ').slice(0,200)));
 await page.getByRole('button',{name:/^New session$/}).locator('visible=true').first().click(); await page.waitForTimeout(800); await page.getByRole('button',{name:/Create/}).click(); 
 await page.waitForTimeout(2500); await page.screenshot({path:OUT+'/s2c_newtab.png'});
 console.log('after new:',await page.evaluate(()=>document.body.innerText.replace(/\n/g,' | ').slice(0,300)));
 await H.openSessionsDialog(page);
 await page.evaluate(()=>window.__insReset());
 const rows=page.locator('button.session-row-open'); const idx=parseInt(process.env.ROW||'12');
 console.log('rows',await rows.count());
 await rows.nth(idx).scrollIntoViewIfNeeded();
 const bp=H.burst(page,'s2c',2500,30); await page.waitForTimeout(150); await rows.nth(idx).click(); const fr=await bp;
 await page.waitForTimeout(1500);
 const d=await H.snapshotIns(page); fs.writeFileSync(OUT+'/s2c.json',JSON.stringify({d,fr}));
 const s=H.summarise(d); console.log(JSON.stringify(s).slice(0,3000)); console.log('shots',fr.length);
 console.log(JSON.stringify([...new Set(d.fr.map(f=>f.sc))]));
 await page.screenshot({path:OUT+'/s2c_final.png'});
 await app.close();})().catch(e=>{console.error(e.message.slice(0,500));process.exit(1)});
