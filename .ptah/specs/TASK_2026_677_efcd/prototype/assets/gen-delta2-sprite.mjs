// Generates delta2-sprite.js (lucide-angular icon data -> inline SVG sprite, ids `d-<name>`). Prototype tool, not product code.
// Run: node gen-delta2-sprite.mjs   (reads D:/projects/ptah-extension/node_modules/lucide-angular/esm2020/icons/<name>.mjs)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const dir = process.env.LUCIDE_DIR || 'D:/projects/ptah-extension/node_modules/lucide-angular/esm2020/icons';
const names = ['bot','workflow','layout-template','server-cog','drafting-compass','users','clipboard-list','palette','flask-conical','search-check','scan-eye','telescope','container','scroll-text','sparkles','eye','square-terminal','loader-circle','check','circle-alert','hand','circle-pause','chevron-down','chevron-right','ellipsis','mouse-pointer-click','arrow-left-right','corner-down-right'];
const esc = (v) => String(v).replace(/"/g, '&quot;');
let out = '';
const missing = [];
for (const n of names) {
  const f = path.join(dir, n + '.mjs');
  if (!fs.existsSync(f)) { missing.push(n); continue; }
  const src = fs.readFileSync(f, 'utf8').split('\n').filter((l) => !l.startsWith('//#')).join('\n');
  const start = src.indexOf('= [', src.indexOf('const ')) + 2;
  const end = src.indexOf('; //eslint', start);
  const body = src.slice(start, end);
  const data = new Function('return ' + body)();
  const kids = data.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([k]) => k !== 'key').map(([k, v]) => `${k}="${esc(v)}"`).join(' ')}/>`).join('');
  out += `<symbol id="d-${n}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-linecap="round" stroke-linejoin="round">${kids}</symbol>`;
}
const js = `/* Generated by gen-delta2-sprite.mjs from lucide-angular 1.0.0 icon data (ids d-<name>). Inline so file:// works offline. */\n(function(){var s=document.createElementNS('http://www.w3.org/2000/svg','svg');s.setAttribute('width','0');s.setAttribute('height','0');s.setAttribute('aria-hidden','true');s.style.position='absolute';s.innerHTML=${JSON.stringify(out)};document.addEventListener('DOMContentLoaded',function(){document.body.prepend(s)});})();\n`;
fs.writeFileSync(path.join(here, 'delta2-sprite.js'), js);
console.log('symbols:', names.length - missing.length, 'missing:', missing.join(',') || 'none');
