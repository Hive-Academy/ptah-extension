function scene(s) {
  const glows = s.glows.map((g) => `<ellipse cx='${g.x}' cy='${g.y}' rx='${g.rx}' ry='${g.ry}' fill='${g.c}' opacity='${g.o}'/>`).join('');
  const ridges = ['far', 'mid', 'near'].map((k, i) => `<path d='${ridgeD[k]}' fill='${s.ridges[i][0]}' opacity='${s.ridges[i][1]}' filter='url(#r${i})'/>`).join('');
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 1600 1000' preserveAspectRatio='xMidYMid slice'>`
    + `<defs><linearGradient id='s' x1='0' y1='0' x2='1' y2='1'><stop offset='0' stop-color='${s.sky[0]}'/><stop offset='.62' stop-color='${s.sky[1]}'/><stop offset='1' stop-color='${s.sky[2]}'/></linearGradient>`
    + `<filter id='g' x='-50%' y='-50%' width='200%' height='200%'><feGaussianBlur stdDeviation='70'/></filter>`
    + `<filter id='r0' x='-5%' y='-20%' width='110%' height='140%'><feGaussianBlur stdDeviation='7'/></filter>`
    + `<filter id='r1' x='-5%' y='-20%' width='110%' height='140%'><feGaussianBlur stdDeviation='5'/></filter>`
    + `<filter id='r2' x='-5%' y='-20%' width='110%' height='140%'><feGaussianBlur stdDeviation='3'/></filter>`
    + `<filter id='n' x='0' y='0' width='100%' height='100%'><feTurbulence type='fractalNoise' baseFrequency='.0032 .0055' numOctaves='3' seed='${s.seed || 7}'/><feColorMatrix type='matrix' values='0 0 0 0 ${s.smoke[0]} 0 0 0 0 ${s.smoke[1]} 0 0 0 0 ${s.smoke[2]} 0 0 0 1.6 -.55'/></filter></defs>`
    + `<rect width='1600' height='1000' fill='url(#s)'/><g filter='url(#g)'>${glows}</g>`
    + `<rect width='1600' height='1000' filter='url(#n)' opacity='${s.smokeO}'/>${ridges}</svg>`;
  return `url("data:image/svg+xml,${encodeURIComponent(svg).replace(/'/g, '%27')}")`;
}
