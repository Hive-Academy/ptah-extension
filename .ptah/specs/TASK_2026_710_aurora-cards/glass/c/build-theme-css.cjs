// Emits theme.css (the DaisyUI-4 compiled equivalent) from theme.config.js.
// usage: node build-theme-css.cjs   (needs culori from the repo's node_modules)
const path = require('path');
const fs = require('fs');
const { oklch, parse } = require('D:/projects/ptah-extension/node_modules/culori');
const themes = require('./theme.config.js');
const map = {
  primary: 'p', 'primary-focus': 'pf', 'primary-content': 'pc',
  secondary: 's', 'secondary-focus': 'sf', 'secondary-content': 'sc',
  accent: 'a', 'accent-focus': 'af', 'accent-content': 'ac',
  neutral: 'n', 'neutral-focus': 'nf', 'neutral-content': 'nc',
  'base-100': 'b1', 'base-200': 'b2', 'base-300': 'b3', 'base-content': 'bc',
  info: 'in', 'info-content': 'inc', success: 'su', 'success-content': 'suc',
  warning: 'wa', 'warning-content': 'wac', error: 'er', 'error-content': 'erc',
};
const fmt = (hex) => {
  const o = oklch(parse(hex));
  return `${(o.l * 100).toFixed(4).replace(/\.?0+$/, '')}% ${o.c.toFixed(4).replace(/\.?0+$/, '') || 0} ${(o.h || 0).toFixed(2).replace(/\.?0+$/, '')}`;
};
let out = '/* Generated by build-theme-css.cjs from theme.config.js — the DaisyUI 4 compiled equivalent. */\n';
const table = [];
for (const [name, t] of Object.entries(themes)) {
  out += `[data-theme=${name}] {\n`;
  for (const [k, v] of Object.entries(t)) {
    if (k === 'color-scheme') out += `  color-scheme: ${v};\n`;
    else if (map[k]) { const c = fmt(v); out += `  --${map[k]}: ${c};\n`; table.push([name, k, v, c]); }
    else out += `  ${k}: ${v};\n`;
  }
  out += '}\n';
}
fs.writeFileSync(path.join(__dirname, 'theme.css'), out);
fs.writeFileSync(path.join(__dirname, '_palette.json'), JSON.stringify(table));
console.log(table.map((r) => r.join(' | ')).join('\n'));
