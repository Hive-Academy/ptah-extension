import { ComponentFixture, TestBed } from '@angular/core/testing';
import type { CloneSummary, DivergedReason } from '@ptah-extension/shared';
import { makeLibraryAgreementFixtures } from '@ptah-extension/shared/testing';

import {
  DivergedReasonComponent,
  PROVENANCE_NO_REBASE_NOTE,
  divergenceUpstreamNote,
} from './diverged-reason.component';

describe('DivergedReasonComponent', () => {
  let fixture: ComponentFixture<DivergedReasonComponent>;

  const reasonEl = (): HTMLElement | null =>
    (fixture.nativeElement as HTMLElement).querySelector<HTMLElement>(
      '[data-testid="diverged-reason"]',
    );

  function render(reason: DivergedReason | null | undefined): void {
    fixture = TestBed.createComponent(DivergedReasonComponent);
    fixture.componentRef.setInput('reason', reason);
    fixture.detectChanges();
  }

  beforeEach(() => {
    TestBed.configureTestingModule({ imports: [DivergedReasonComponent] });
  });

  it('states a wizard regeneration and that the edits are kept', () => {
    render({ kind: 'setup-wizard' });
    expect(reasonEl()?.textContent?.trim()).toBe(
      'Source regenerated by the setup wizard. Your edits are kept in the Library copy.',
    );
  });

  it('names the plugin for a plugin update (shared fixture)', () => {
    const { pluginUpdateDiverged } = makeLibraryAgreementFixtures();
    render(pluginUpdateDiverged.listClones.clones[0].divergedReason);
    expect(reasonEl()?.textContent?.trim()).toBe(
      'Source updated by the plugin Acme Toolkit. Your edits are kept in the Library copy.',
    );
  });

  it.each<DivergedReason | null | undefined>([
    { kind: 'source-changed' },
    null,
    undefined,
  ])('renders nothing for %j', (reason) => {
    render(reason);
    expect(reasonEl()).toBeNull();
  });
});

describe('divergenceUpstreamNote', () => {
  const base = (overrides: Partial<CloneSummary> = {}): CloneSummary => ({
    slug: 'mine',
    kind: 'agent',
    cloneStatus: 'authored',
    diverged: true,
    invocationCount: 0,
    successRate: null,
    lastEnhancedAt: null,
    historyCount: 0,
    pendingSourceHash: null,
    enhanceMinInvocations: 5,
    enhanceCooldownUntil: null,
    ...overrides,
  });

  it('passes no note through as no note', () => {
    expect(
      divergenceUpstreamNote(base({ provenance: { kind: 'setup-wizard' } }), null),
    ).toBeNull();
  });

  it('keeps the gated note when there is no recorded origin', () => {
    expect(divergenceUpstreamNote(base(), 'gated')).toBe('gated');
  });

  it('never says "no upstream source" when a recorded origin exists', () => {
    const note = divergenceUpstreamNote(
      base({ provenance: { kind: 'setup-wizard' } }),
      'Authored here — this entry has no upstream source.',
    );
    expect(note).toBe(PROVENANCE_NO_REBASE_NOTE);
    expect(note).not.toContain('no upstream source');
  });
});
