/**
 * DivergedReasonComponent (C8) — why a diverged Library copy diverged.
 *
 * Pure presentational atom. The sentence comes from `divergedReasonText`
 * (`@ptah-extension/shared`) plus the fixed "Your edits are kept in the
 * Library copy." (design-spec 3.7). A reason without specific copy
 * (`source-changed`) or an absent reason renders nothing, so the parent's
 * generic divergence wording stands alone.
 *
 * Also home of {@link divergenceUpstreamNote}, the provenance-aware wording of
 * the "cannot rebase" note shared by the card and the drawer.
 */
import {
  ChangeDetectionStrategy,
  Component,
  computed,
  input,
} from '@angular/core';
import {
  divergedReasonText,
  type CloneSummary,
  type DivergedReason,
} from '@ptah-extension/shared';

/** Appended to every specific diverged reason (design-spec 3.7). */
export const DIVERGED_EDITS_KEPT = 'Your edits are kept in the Library copy.';

/**
 * Note shown instead of the gating's "no upstream source" sentence when the
 * entry has a recorded origin: saying "no upstream source" next to an origin
 * badge (and a "Source regenerated by ..." line) contradicts the card.
 */
export const PROVENANCE_NO_REBASE_NOTE =
  'Rebase is not available for this entry. Keep mine marks this divergence ' +
  'resolved and leaves your copy as it is.';

/**
 * The card / drawer upstream note. `gatedNote` is
 * `cloneActionModel(clone).upstreamNote`; the gating itself
 * (`hasUpstreamSource`) is not changed, only its wording when a recorded
 * origin exists.
 */
export function divergenceUpstreamNote(
  clone: CloneSummary,
  gatedNote: string | null,
): string | null {
  if (gatedNote === null) return null;
  return clone.provenance === undefined ? gatedNote : PROVENANCE_NO_REBASE_NOTE;
}

@Component({
  selector: 'ptah-diverged-reason',
  standalone: true,
  changeDetection: ChangeDetectionStrategy.OnPush,
  template: `
    @if (sentence(); as text) {
      <p
        class="rounded-md bg-base-300 px-2 py-1.5 text-[11px] text-base-content"
        data-testid="diverged-reason"
      >
        {{ text }}
      </p>
    }
  `,
})
export class DivergedReasonComponent {
  /** Why the copy diverged; `null` / `undefined` render nothing. */
  public readonly reason = input<DivergedReason | null | undefined>(null);

  protected readonly sentence = computed<string | null>(() => {
    const text = divergedReasonText(this.reason());
    return text === null ? null : `${text} ${DIVERGED_EDITS_KEPT}`;
  });
}
