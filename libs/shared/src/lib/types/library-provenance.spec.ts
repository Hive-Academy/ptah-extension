import {
  divergedReasonText,
  orphanedText,
  provenanceLabel,
  type LibraryProvenance,
} from './library-provenance';

const plugin = (
  state: 'active' | 'turned-off' | 'uninstalled',
): LibraryProvenance => ({
  kind: 'plugin',
  pluginId: 'former-helper-plugin',
  name: 'Former Helper',
  state,
});

describe('provenanceLabel', () => {
  it.each<[LibraryProvenance | null | undefined, string]>([
    [{ kind: 'setup-wizard' }, 'Setup wizard'],
    [plugin('active'), 'Plugin: Former Helper'],
    [plugin('turned-off'), 'Plugin: Former Helper'],
    [plugin('uninstalled'), 'Plugin: Former Helper'],
    [{ kind: 'skills-sh', source: 'acme/skills' }, 'skills.sh: acme/skills'],
    [{ kind: 'workspace' }, 'Workspace file'],
    [undefined, 'Workspace file'],
    [null, 'Workspace file'],
  ])('labels %j as %s', (provenance, label) => {
    expect(provenanceLabel(provenance)).toBe(label);
  });

  it('uses the recorded display name, not the plugin id', () => {
    expect(provenanceLabel(plugin('uninstalled'))).not.toContain(
      'former-helper-plugin',
    );
  });
});

describe('divergedReasonText', () => {
  it('names the setup wizard', () => {
    expect(divergedReasonText({ kind: 'setup-wizard' })).toBe(
      'Source regenerated by the setup wizard.',
    );
  });

  it('names the plugin', () => {
    expect(
      divergedReasonText({ kind: 'plugin', pluginName: 'Acme Toolkit' }),
    ).toBe('Source updated by the plugin Acme Toolkit.');
  });

  it.each([{ kind: 'source-changed' as const }, null, undefined])(
    'returns null for %j',
    (reason) => {
      expect(divergedReasonText(reason)).toBeNull();
    },
  );
});

describe('orphanedText', () => {
  it('words a turned-off plugin', () => {
    expect(orphanedText(plugin('turned-off'))).toBe(
      'The plugin "Former Helper" is turned off. Your edits are kept here.',
    );
  });

  it('words an uninstalled plugin differently from a turned-off one', () => {
    expect(orphanedText(plugin('uninstalled'))).toBe(
      'The plugin "Former Helper" is no longer installed. Your edits are kept here.',
    );
  });

  it.each<LibraryProvenance | null | undefined>([
    plugin('active'),
    { kind: 'setup-wizard' },
    { kind: 'skills-sh', source: 'acme/skills' },
    { kind: 'workspace' },
    null,
    undefined,
  ])('returns null for %j', (provenance) => {
    expect(orphanedText(provenance)).toBeNull();
  });
});
