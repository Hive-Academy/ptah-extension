/**
 * Library provenance: where a Library item came from, and why a diverged one
 * diverged (TASK_2026_701_9e4b, B1).
 *
 * One label function for the Library, the Marketplace and the wizard
 * completion, so the three surfaces cannot word the same origin differently.
 * The label is derived only from the recorded origin marker, never from names
 * or paths. Every string here is the exact copy of design-spec section 5.
 */

/** Plugin lifecycle as seen from one of its Library copies. */
export type LibraryPluginState = 'active' | 'turned-off' | 'uninstalled';

/**
 * The recorded origin of a Library item.
 *
 * - `setup-wizard`: written by wizard generation (stays so after a hand edit;
 *   Diverged is a separate badge).
 * - `plugin`: mirrored from a plugin. `name` is the live display name, else the
 *   name recorded when the copy was made, else the plugin id. A turned-off or
 *   uninstalled plugin keeps its label; `state` drives the status word.
 * - `skills-sh`: installed from skills.sh. `source` is `owner/repo`.
 * - `workspace`: no Ptah origin marker (legacy, hand-made, pack or kept file).
 */
export type LibraryProvenance =
  | { kind: 'setup-wizard' }
  | {
      kind: 'plugin';
      pluginId: string;
      name: string;
      state: LibraryPluginState;
    }
  | { kind: 'skills-sh'; source: string }
  | { kind: 'workspace' };

/**
 * Why a diverged Library copy diverged.
 *
 * - `setup-wizard`: the wizard regenerated the source.
 * - `plugin`: the plugin `pluginName` updated the source.
 * - `source-changed`: the source changed for another reason; there is no
 *   specific copy for it, so no reason line is shown.
 */
export type DivergedReason =
  | { kind: 'setup-wizard' }
  | { kind: 'plugin'; pluginName: string }
  | { kind: 'source-changed' };

/**
 * Badge label for a Library item. An absent provenance (the resolver failed or
 * an older host) reads as "Workspace file", the label for an item with no
 * Ptah marker.
 */
export function provenanceLabel(
  provenance: LibraryProvenance | null | undefined,
): string {
  if (provenance === null || provenance === undefined) return 'Workspace file';
  switch (provenance.kind) {
    case 'setup-wizard':
      return 'Setup wizard';
    case 'plugin':
      return `Plugin: ${provenance.name}`;
    case 'skills-sh':
      return `skills.sh: ${provenance.source}`;
    case 'workspace':
      return 'Workspace file';
  }
}

/** The diverged-reason sentence, or null when no specific reason is known. */
export function divergedReasonText(
  reason: DivergedReason | null | undefined,
): string | null {
  if (reason === null || reason === undefined) return null;
  switch (reason.kind) {
    case 'setup-wizard':
      return 'Source regenerated by the setup wizard.';
    case 'plugin':
      return `Source updated by the plugin ${reason.pluginName}.`;
    case 'source-changed':
      return null;
  }
}

/**
 * The plugin-state sentence for a copy whose plugin is turned off or no longer
 * installed, or null when the item has no such plugin. Turned off and
 * uninstalled deliberately use different copy.
 */
export function orphanedText(
  provenance: LibraryProvenance | null | undefined,
): string | null {
  if (provenance?.kind !== 'plugin') return null;
  switch (provenance.state) {
    case 'turned-off':
      return `The plugin "${provenance.name}" is turned off. Your edits are kept here.`;
    case 'uninstalled':
      return `The plugin "${provenance.name}" is no longer installed. Your edits are kept here.`;
    case 'active':
      return null;
  }
}
