#!/usr/bin/env node
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const scenarioDir = join(root, 'libs/web/landing/src/lib/live-demo/scenarios');
const check = process.argv.includes('--check');
let stale = false;

for (const filename of (await readdir(scenarioDir)).filter((name) => name.endsWith('.json')).sort()) {
  const id = filename.slice(0, -5);
  const json = JSON.parse(await readFile(join(scenarioDir, filename), 'utf8'));
  if (json.id !== id || !/^[a-z0-9-]+$/.test(id)) throw new Error(`Invalid scenario id: ${filename}`);
  const generated = `// Generated by scripts/landing/generate-live-demo-types.mjs. Do not edit.\nimport type { ReplayScenario } from '../scenario/replay-scenario.types';\n\nexport const scenario = ${JSON.stringify(json, null, 2)} satisfies ReplayScenario;\n`;
  const output = join(scenarioDir, `${id}.scenario.generated.ts`);
  if (check) {
    let current = '';
    try { current = await readFile(output, 'utf8'); } catch { /* missing is stale */ }
    if (current !== generated) { console.error(`Stale generated scenario: ${output}`); stale = true; }
  } else {
    await writeFile(output, generated);
  }
}
if (stale) process.exitCode = 1;
